#!/usr/bin/env python3
"""Regenerate pages/reference-cli.md from the MeshBench repository.

    python3 tools/sync-cli.py [path-to-meshbench-checkout] [--stdout]

Sixteen commands and a hundred and sixty-four flags between them, none of which
can be maintained here. The page is generated in the MeshBench repository by
`tools/flagdoc/flagdoc.py`, which builds the binary and asks it for the flag
set every command declares, so the reference cannot describe a flag the binary
does not have. That has to happen beside the code: it needs a Go toolchain and
a checkout, and this repository's build has neither.

So what happens here is a copy, with the markers the generator leaves for its
own use taken out. gen.py refuses to build if a checkout is reachable and this
copy is stale, which is the same guard the other generated pages have.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_REPO = os.path.join(os.path.dirname(HERE), "meshcoresim")
OUT = os.path.join(HERE, "pages", "reference-cli.md")
SOURCE = os.path.join("docs", "cli-reference.md")

HEADER = """<!--
  GENERATED from meshcoresim/%s - do not edit this file.
  That page is itself generated from the flag declarations by
  tools/flagdoc/flagdoc.py. Run tools/sync-cli.py after it changes.
-->
""" % SOURCE

# The generator's own marks. The block fences tell it which half of its
# document it owns, and each count marker sits inline against the number it
# keeps true. Neither means anything to a reader, and an inline comment is not
# at the start of its line, so gen.py would escape it into the page rather than
# skip it.
MARKS = [
    re.compile(r"<!--flagdoc:[a-z]+-->"),
    re.compile(r"^<!-- (?:BEGIN|END) GENERATED CLI -->\n", re.M),
]


def build(text):
    for mark in MARKS:
        text = mark.sub("", text)
    # The fences left a blank line where each stood; two in a row read as a
    # paragraph break that was never written.
    text = re.sub(r"\n{3,}", "\n\n", text)
    return HEADER + text


def main():
    argv = [a for a in sys.argv if a != "--stdout"]
    root = argv[1] if len(argv) > 1 else os.environ.get("MESHBENCH_REPO", DEFAULT_REPO)
    src = os.path.join(root, SOURCE)
    if not os.path.exists(src):
        sys.exit("no MeshBench checkout at %s\n"
                 "pass one as an argument or set MESHBENCH_REPO" % root)
    with open(src) as f:
        out = build(f.read())
    if "--stdout" in sys.argv:
        sys.stdout.write(out)
        return
    with open(OUT, "w") as f:
        f.write(out)
    print("wrote %s from %s" % (os.path.relpath(OUT, HERE), src))


if __name__ == "__main__":
    main()
