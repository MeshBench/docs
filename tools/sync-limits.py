#!/usr/bin/env python3
"""Regenerate pages/what-it-does-not-do.md from the MeshBench repository.

    python3 tools/sync-limits.py [path-to-meshbench-checkout] [--stdout]

The honesty document is the one page that cannot be authored here. CLAUDE.md in
the MeshBench repository makes keeping it accurate a rule *as the model
changes*, and the application itself prints its path to the user, so the source
of truth has to sit beside the code. This copies it in and rewrites the handful
of references that only make sense inside that repository.

gen.py refuses to build if the source is reachable and this copy is stale, so
the two cannot drift apart unnoticed.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_REPO = os.path.join(os.path.dirname(HERE), "meshcoresim")
OUT = os.path.join(HERE, "pages", "what-it-does-not-do.md")
SOURCE = os.path.join("docs", "shortcomings.md")

HEADER = """<!--
  GENERATED from meshcoresim/%s - do not edit this file.
  Run tools/sync-limits.py after changing the source.
-->
""" % SOURCE

# References that mean something inside the code repository and nothing here.
REWRITE = [
    (r"docs/waveform-source-of-truth\.md", "[the waveform](waveform.html)"),
    (r"`?internal/lora`?", "the LoRa coding chain"),
    (r"`?internal/validate`?", "the validation package"),
    (r"The reason this document exists is in `CLAUDE\.md`: ",
     "The reason this page exists: "),
]


def repo_root(argv):
    if len(argv) > 1:
        return argv[1]
    return os.environ.get("MESHBENCH_REPO", DEFAULT_REPO)


def build(src_text):
    out = src_text
    for pattern, replacement in REWRITE:
        out = re.sub(pattern, replacement, out)
    # The page is titled for what a reader is looking for, not for the file it
    # came from.
    out = re.sub(r"\A# Shortcomings", "# What it does not do", out)
    return HEADER + out


def main():
    argv = [a for a in sys.argv if a != "--stdout"]
    to_stdout = "--stdout" in sys.argv
    root = repo_root(argv)
    src = os.path.join(root, SOURCE)
    if not os.path.exists(src):
        sys.exit("no MeshBench checkout at %s\n"
                 "pass one as an argument or set MESHBENCH_REPO" % root)
    with open(src) as f:
        text = f.read()
    out = build(text)
    if to_stdout:
        sys.stdout.write(out)
        return
    with open(OUT, "w") as f:
        f.write(out)
    print("wrote %s from %s" % (os.path.relpath(OUT, HERE), src))


if __name__ == "__main__":
    main()
